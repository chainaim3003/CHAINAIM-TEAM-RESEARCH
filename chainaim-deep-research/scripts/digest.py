"""digest.py — weekly digest of what was added to the KB (no AI).

Why (DESIGN/07-build-plan.md, PR-6 automation; the agent stays AI-free):
    A short Markdown overview of everything extracted in the last N days — titles, source links,
    transcript/prompt links and whether a summary has been saved yet — so you can see at a glance
    what to read or paste into your AI this week. No content is generated; it only lists facts
    from the manifest and the files on disk.

Output: <kb_dir>/kb/digests/<ISO-year>-W<week>.md (overwritten for the same week on re-run).

Usage (run from chainaim-deep-research/):
    uv run scripts/digest.py --dry-run           # print the digest, write nothing
    uv run scripts/digest.py                     # last 7 days -> kb/digests/<year>-W<ww>.md
    uv run scripts/digest.py --days 30 --kb-dir ../Transcript

Flags (Rule 8):
    --config PATH   config.yaml (default: next to scripts/)
    --kb-dir PATH   override output.kb_dir
    --days N        look-back window in days (default 7)
    --out DIR       output folder, relative to kb_dir (default kb/digests)
    --dry-run       print the digest instead of writing it
Exit codes: 0 success (also when nothing new), 1 manifest missing.
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ROOT))

from orchestrate import load_config, resolve_paths  # noqa: E402
from build_kb_pack import summary_status           # noqa: E402


def _parse_ts(value: str) -> Optional[datetime]:
    try:
        dt = datetime.fromisoformat(value)
    except (TypeError, ValueError):
        return None
    return dt if dt.tzinfo else dt.replace(tzinfo=timezone.utc)


def build_digest(data: Dict[str, Dict[str, Any]], kb_dir: Path, *, days: int, now: datetime,
                 prompts_rel: str = "kb/prompts", highlights_rel: str = "kb/highlights") -> str:
    """Return the digest Markdown for entries extracted in (now - days, now]."""
    since = now - timedelta(days=days)
    rows: List[Dict[str, str]] = []
    for key, e in data.items():
        ts = _parse_ts(e.get("ts", ""))
        if e.get("status") != "extracted" or ts is None or not (since < ts <= now):
            continue
        full = (e.get("full_paths") or {})
        rel_full = full.get("txt") or full.get("md") or next(iter(full.values()), "")
        stem = e.get("stem") or Path(rel_full).stem
        status = summary_status(kb_dir / highlights_rel / f"{stem}.md")
        rows.append({"ts": ts.strftime("%Y-%m-%d"), "kind": {"github_repo": "GitHub", "arxiv_paper": "arXiv", "web_article": "Web"}.get(e.get("kind") or "", "YouTube"),
                     "title": (e.get("title") or stem).replace("|", "\\|"), "url": e.get("source_url", ""),
                     "full": rel_full[3:] if rel_full.startswith("kb/") else rel_full,
                     "prompt": f"{prompts_rel[3:] if prompts_rel.startswith('kb/') else prompts_rel}/{stem}.prompt.md",
                     "summary": {"ok": "yes", "check": "CHECK", "missing": "no"}[status]})
    rows.sort(key=lambda r: (r["ts"], r["title"].lower()), reverse=True)
    iso = now.isocalendar()
    done = sum(1 for r in rows if r["summary"] == "yes")
    lines = [
        f"# Weekly digest {iso[0]}-W{iso[1]:02d}",
        "",
        f"Added {since.strftime('%Y-%m-%d')} .. {now.strftime('%Y-%m-%d')} (last {days} days): "
        f"{len(rows)} item(s), {done} with a saved summary, {len(rows) - done} still to summarise.",
        "",
        "Generated by scripts/digest.py (no AI). Links are relative to the kb/ folder.",
        "",
    ]
    if not rows:
        lines.append("Nothing new in this period.")
    else:
        lines += ["| Added | Type | Title | Source | Transcript | Prompt | Summary saved |",
                  "|-------|------|-------|--------|------------|--------|---------------|"]
        for r in rows:
            lines.append(f"| {r['ts']} | {r['kind']} | {r['title']} | [link]({r['url']}) | "
                         f"[file](<{r['full']}>) | [prompt](<{r['prompt']}>) | {r['summary']} |")
    return "\n".join(lines) + "\n"


def run(args: argparse.Namespace) -> int:
    cfg = load_config(Path(args.config))
    paths = resolve_paths(cfg, args.kb_dir)
    if not paths["manifest"].exists():
        print(f"manifest not found: {paths['manifest']}")
        return 1
    data = json.loads(paths["manifest"].read_text(encoding="utf-8"))
    now = datetime.now(timezone.utc)
    out_cfg = cfg.get("output", {})
    md = build_digest(data, paths["kb_dir"], days=args.days, now=now,
                      prompts_rel=out_cfg.get("prompts_dir", "kb/prompts"),
                      highlights_rel=out_cfg.get("highlights_dir", "kb/highlights"))
    if args.dry_run:
        print(md)
        return 0
    iso = now.isocalendar()
    out_dir = paths["kb_dir"] / args.out
    out_dir.mkdir(parents=True, exist_ok=True)
    target = out_dir / f"{iso[0]}-W{iso[1]:02d}.md"
    target.write_text(md, encoding="utf-8")
    print(f"digest written: {target}")
    print(md.splitlines()[2])
    return 0


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="digest", description="Weekly digest of new KB items (no AI).")
    p.add_argument("--config", default=str(ROOT / "config.yaml"))
    p.add_argument("--kb-dir", default=None)
    p.add_argument("--days", type=int, default=7)
    p.add_argument("--out", default="kb/digests")
    p.add_argument("--dry-run", action="store_true")
    return p


if __name__ == "__main__":
    raise SystemExit(run(build_parser().parse_args()))
